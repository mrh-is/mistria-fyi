import * as fontkit from "fontkit";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
// Generates the per-locale `@font-face` stylesheets under `src/lib/fonts/` and stages every woff2
// chunk they reference for upload to R2 (`assets.mistria.fyi`).
//
//   pnpm run fonts:build [--input <dir>] [--out <dir>] [--skip-sliced]
//
// Fontsource families are copied from `node_modules/@fontsource/*` with their pre-sliced
// `unicode-range` chunks. The Simplified Chinese faces are sliced here with the same unicode-range
// table Google Fonts uses for Noto Sans SC (`simplified-chinese-unicode-ranges.json`).
//
// Nothing is uploaded by this script; see `upload-locale-fonts.sh`.
import { parseArgs } from "node:util";
import subsetFont from "subset-font";

import { ASSET_ORIGIN, ASSET_PREFIX, FONTSOURCE_FONTS, SLICED_FONTS } from "./manifest.js";

import type { FontLocale, FontsourceFont, SlicedFont } from "./manifest.js";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const CSS_DIR = path.join(ROOT, "src", "lib", "fonts");
const RANGES_FILE = fileURLToPath(
  new URL("./simplified-chinese-unicode-ranges.json", import.meta.url),
);

interface FontFace {
  family: string;
  /** R2 key relative to the bucket root. */
  key: string;
  style: string;
  unicodeRange: string;
  weight: string;
}

interface UnicodeRangeTable {
  ranges: { id: number | string; range: string }[];
}

const { values: args } = parseArgs({
  options: {
    input: { type: "string", default: path.join(ROOT, "scripts", "locale-fonts", "input") },
    out: { type: "string", default: path.join(ROOT, ".locale-fonts-dist") },
    "skip-sliced": { type: "boolean", default: false },
  },
});

/** Expands a CSS `unicode-range` list into the characters the font actually has glyphs for. */
function coveredText(font: fontkit.Font, range: string): string {
  let text = "";
  for (const part of range.split(",")) {
    const match = /^U\+([0-9a-f]+)(?:-([0-9a-f]+))?$/i.exec(part);
    if (!match) throw new Error(`Unparseable unicode-range segment: ${part}`);
    const start = parseInt(match[1], 16);
    const end = match[2] ? parseInt(match[2], 16) : start;
    for (let codePoint = start; codePoint <= end; codePoint += 1) {
      if (font.hasGlyphForCodePoint(codePoint)) text += String.fromCodePoint(codePoint);
    }
  }
  return text;
}

async function main(): Promise<void> {
  const facesByLocale = new Map<FontLocale, FontFace[]>();
  const add = (locale: FontLocale, faces: FontFace[]): void => {
    facesByLocale.set(locale, [...(facesByLocale.get(locale) ?? []), ...faces]);
  };

  for (const font of FONTSOURCE_FONTS) {
    add(font.locale, await stageFontsource(font));
  }
  if (!args["skip-sliced"]) {
    const table = JSON.parse(await readFile(RANGES_FILE, "utf8")) as UnicodeRangeTable;
    for (const font of SLICED_FONTS) {
      add(font.locale, await stageSliced(font, table));
    }
  }

  await mkdir(CSS_DIR, { recursive: true });
  for (const [locale, faces] of facesByLocale) {
    const file = path.join(CSS_DIR, `locale-fonts-${locale}.css`);
    await writeFile(file, renderStylesheet(locale, faces));
    console.log(`${path.relative(ROOT, file)}: ${faces.length} faces`);
  }
  console.log(`Staged upload directory: ${path.relative(ROOT, args.out)}`);
}

function renderStylesheet(locale: FontLocale, faces: FontFace[]): string {
  const header = `/* Generated by scripts/locale-fonts/build-locale-fonts.ts for lang="${locale}". Do not edit. */\n`;
  const blocks = faces.map(
    (face) =>
      `@font-face{font-family:"${face.family}";font-style:${face.style};font-weight:${face.weight};font-display:swap;src:url(${ASSET_ORIGIN}/${face.key}) format("woff2");unicode-range:${face.unicodeRange}}`,
  );
  return `${header}${blocks.join("\n")}\n`;
}

async function stageFile(key: string, write: (target: string) => Promise<void>): Promise<void> {
  const target = path.join(args.out, key);
  await mkdir(path.dirname(target), { recursive: true });
  await write(target);
}

async function stageFontsource(font: FontsourceFont): Promise<FontFace[]> {
  const packageDir = path.join(ROOT, "node_modules", "@fontsource", font.package);
  const { version } = JSON.parse(await readFile(path.join(packageDir, "package.json"), "utf8")) as {
    version: string;
  };
  const keyPrefix = `${ASSET_PREFIX}/${font.package}-${version}`;
  const faces: FontFace[] = [];

  for (const entry of font.faces) {
    const css = await readFile(path.join(packageDir, `${entry}.css`), "utf8");
    for (const block of css.split("@font-face").slice(1)) {
      const family = /font-family:\s*'([^']+)'/.exec(block)?.[1];
      const style = /font-style:\s*(\w+)/.exec(block)?.[1];
      const weight = /font-weight:\s*([\d ]+)/.exec(block)?.[1];
      const unicodeRange = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      if (!family || !style || !weight || !unicodeRange || !file) {
        throw new Error(
          `Unrecognized @font-face block in @fontsource/${font.package}/${entry}.css`,
        );
      }
      const key = `${keyPrefix}/${file}`;
      await stageFile(key, (target) => copyFile(path.join(packageDir, "files", file), target));
      faces.push({ family, key, style, unicodeRange: unicodeRange.replace(/\s+/g, ""), weight });
    }
  }
  return faces;
}

async function stageSliced(font: SlicedFont, table: UnicodeRangeTable): Promise<FontFace[]> {
  const keyPrefix = `${ASSET_PREFIX}/${font.slug}-${font.version}`;
  const faces: FontFace[] = [];

  for (const face of font.faces) {
    const source = path.join(args.input, face.file);
    const buffer = await readFile(source);
    const parsed = fontkit.create(buffer);
    if (!("hasGlyphForCodePoint" in parsed)) {
      throw new Error(`${face.file} is a font collection; expected a single face`);
    }
    let emitted = 0;

    for (const { id, range } of table.ranges) {
      const text = coveredText(parsed, range);
      if (text.length === 0) continue;
      const woff2 = await subsetFont(buffer, text, { targetFormat: "woff2" });
      const key = `${keyPrefix}/${font.slug}-${id}-${face.weight}-${face.style}.woff2`;
      await stageFile(key, (target) => writeFile(target, woff2));
      faces.push({
        family: font.family,
        key,
        style: face.style,
        unicodeRange: range,
        weight: String(face.weight),
      });
      emitted += 1;
    }
    console.log(`${font.family} ${face.weight}: ${emitted}/${table.ranges.length} chunks`);
  }
  return faces;
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
