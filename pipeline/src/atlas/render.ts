import { compareStrings } from "../ordering.js";
import { topFolder } from "./inventory.js";

import type { AtlasDiff, FiddleFileDiff } from "./diff.js";
import type { AssetAtlas, FiddleFileInventory } from "./inventory.js";

// Keys sharing one shape are listed together once a group reaches this size.
const GROUP_MIN_KEYS = 4;
const GROUP_EXAMPLE_KEYS = 3;
// Lists longer than this name the first entries and defer the rest to the JSON output.
const LIST_LIMIT = 40;
const SHAPE_LIMIT = 400;
// Characters of unchanged shape kept on each side of a reshaped key's difference.
const DELTA_CONTEXT = 40;

const CLAIM_NOTE =
  "Claims come from a static scan of `pipeline/src`: a module that names a root, a path inside it, or an ancestor of it. A claim means the module reaches the file, not that it reads every key.";

/** Renders one version's atlas as Markdown. */
export function renderAtlas(atlas: AssetAtlas): string {
  const lines = [
    `# Asset atlas: v${atlas.version}`,
    "",
    "Generated by `pnpm run pipeline:atlas`. The structure is documented in `docs/game-asset-format.md`.",
    "",
    "## Folders",
    "",
    "| Folder | Files | Extensions |",
    "| --- | ---: | --- |",
  ];
  for (const folder of atlas.folders) {
    const extensions = Object.entries(folder.extensions)
      .map(([extension, count]) => `${extension} ${count}`)
      .join(", ");
    lines.push(`| \`${folder.name}\` | ${folder.files.length} | ${extensions} |`);
  }

  const claimed = atlas.fiddle.filter((file) => file.claims.length > 0).length;
  lines.push(
    "",
    "## Fiddle roots",
    "",
    `${atlas.fiddle.length} roots, ${claimed} claimed by the pipeline. ${CLAIM_NOTE}`,
    "",
    "| Root | File | Keys | Claimed by |",
    "| --- | --- | ---: | --- |",
  );
  for (const file of atlas.fiddle) {
    const claims = file.claims.length > 0 ? claimModules(file).join(", ") : "";
    lines.push(
      `| \`${file.rootPath}\` | \`${file.sourceFile}\` | ${Object.keys(file.keys).length} | ${claims} |`,
    );
  }

  for (const file of atlas.fiddle) {
    lines.push("", `### \`${file.rootPath}\``, "", `Source: \`fiddle/${file.sourceFile}\``);
    if (file.claims.length > 0) {
      const claims = file.claims.map(({ module, reference }) => `\`${module}\` (\`${reference}\`)`);
      lines.push("", `Claimed by: ${claims.join(", ")}`);
    }
    lines.push("", ...renderKeys(file.keys));
  }
  return `${lines.join("\n")}\n`;
}

function claimModules(file: FiddleFileInventory): string[] {
  return [...new Set(file.claims.map((claim) => `\`${claim.module}\``))];
}

/** Lists each key with its shape, collapsing large groups of keys that share one shape. */
function renderKeys(keys: Record<string, string>): string[] {
  const keysByShape = new Map<string, string[]>();
  for (const [key, shape] of Object.entries(keys)) {
    keysByShape.set(shape, [...(keysByShape.get(shape) ?? []), key]);
  }
  const groups = [...keysByShape].toSorted(([, a], [, b]) => compareStrings(a[0], b[0]));
  if (groups.length === 0) return ["(empty)"];
  return groups.flatMap(([shape, groupKeys]) => {
    const shown = `\`${truncate(shape)}\``;
    if (groupKeys.length < GROUP_MIN_KEYS) {
      return groupKeys.map((key) => `- \`${key}\`: ${shown}`);
    }
    const examples = groupKeys
      .slice(0, GROUP_EXAMPLE_KEYS)
      .map((key) => `\`${key}\``)
      .join(", ");
    return [`- ${groupKeys.length} keys (${examples}, …): ${shown}`];
  });
}

/** Renders the comparison of two versions' atlases as Markdown. */
export function renderDiff(diff: AtlasDiff): string {
  const lines = [
    `# Asset atlas diff: v${diff.before} → v${diff.after}`,
    "",
    "Generated by `pnpm run pipeline:atlas`. Reshaped keys compare shape summaries, not values; a value-only change does not appear here.",
    "",
    "## Summary",
    "",
    `- Files added: ${diff.files.added.length}`,
    `- Files removed: ${diff.files.removed.length}`,
    `- Fiddle roots added: ${diff.fiddle.added.length}`,
    `- Fiddle roots removed: ${diff.fiddle.removed.length}`,
    `- Fiddle roots with changed keys: ${diff.fiddle.changed.length}`,
    ...renderFileList("Files added", diff.files.added),
    ...renderFileList("Files removed", diff.files.removed),
    ...renderList("Fiddle roots added", diff.fiddle.added),
    ...renderList("Fiddle roots removed", diff.fiddle.removed),
  ];
  if (diff.fiddle.changed.length > 0) {
    lines.push("", "## Changed fiddle roots");
    for (const file of diff.fiddle.changed) lines.push(...renderFileDiff(file));
  }
  return `${lines.join("\n")}\n`;
}

function renderFileList(title: string, files: readonly string[]): string[] {
  if (files.length === 0) return [];
  const filesByFolder = new Map<string, string[]>();
  for (const file of files) {
    const folder = topFolder(file);
    filesByFolder.set(folder, [...(filesByFolder.get(folder) ?? []), file]);
  }
  const lines = ["", `## ${title}`];
  for (const [folder, folderFiles] of filesByFolder) {
    lines.push("", `### \`${folder}\` (${folderFiles.length})`, "", ...limitedList(folderFiles));
  }
  return lines;
}

function renderList(title: string, values: readonly string[]): string[] {
  if (values.length === 0) return [];
  return ["", `## ${title}`, "", ...limitedList(values)];
}

function renderFileDiff(file: FiddleFileDiff): string[] {
  const lines = ["", `### \`${file.rootPath}\``];
  if (file.addedKeys.length > 0) {
    lines.push("", `Keys added (${file.addedKeys.length}):`, "", ...limitedList(file.addedKeys));
  }
  if (file.removedKeys.length > 0) {
    lines.push(
      "",
      `Keys removed (${file.removedKeys.length}):`,
      "",
      ...limitedList(file.removedKeys),
    );
  }
  if (file.reshapedKeys.length > 0) {
    lines.push("", `Keys reshaped (${file.reshapedKeys.length}):`, "");
    for (const { after, before, key } of file.reshapedKeys.slice(0, LIST_LIMIT)) {
      const [beforeDelta, afterDelta] = shapeDelta(before, after);
      lines.push(`- \`${key}\`: \`${beforeDelta}\` → \`${afterDelta}\``);
    }
    lines.push(...overflowNote(file.reshapedKeys.length));
  }
  return lines;
}

function limitedList(values: readonly string[]): string[] {
  return [
    ...values.slice(0, LIST_LIMIT).map((value) => `- \`${value}\``),
    ...overflowNote(values.length),
  ];
}

function overflowNote(count: number): string[] {
  return count > LIST_LIMIT ? [`- …and ${count - LIST_LIMIT} more (see the JSON output)`] : [];
}

/**
 * Trims two shapes to the span where they differ, keeping a little context on each side, so a
 * one-field change in a wide table stays visible.
 */
export function shapeDelta(before: string, after: string): [string, string] {
  let start = 0;
  while (start < before.length && start < after.length && before[start] === after[start]) start++;
  let end = 0;
  while (
    end < before.length - start &&
    end < after.length - start &&
    before[before.length - 1 - end] === after[after.length - 1 - end]
  ) {
    end++;
  }
  const from = Math.max(0, start - DELTA_CONTEXT);
  const trim = (shape: string): string => {
    const to = Math.min(shape.length, shape.length - end + DELTA_CONTEXT);
    return `${from > 0 ? "…" : ""}${truncate(shape.slice(from, to))}${to < shape.length ? "…" : ""}`;
  };
  return [trim(before), trim(after)];
}

function truncate(shape: string): string {
  return shape.length > SHAPE_LIMIT ? `${shape.slice(0, SHAPE_LIMIT)}…` : shape;
}
