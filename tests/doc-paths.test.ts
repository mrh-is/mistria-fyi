import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, posix, resolve } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Keeps prose docs from drifting away from the repo: relative Markdown links must resolve, and
 * backticked tokens that look like repo paths must exist. `docs/superpowers/` is historical & is
 * deliberately not scanned.
 */

const root = join(import.meta.dirname, "..");

const markdownIn = (directory: string): string[] =>
  readdirSync(join(root, directory))
    .filter((name) => name.endsWith(".md"))
    .map((name) => join(directory, name));

const docs = [
  "AGENTS.md",
  "CONTRIBUTING.md",
  "README.md",
  ...markdownIn("docs"),
  ...markdownIn("pipeline"),
];

// Top-level entries, so a bare `package.json` or `src` counts as a path without a `/`.
const rootEntries = new Set(readdirSync(root));

/**
 * Gitignored paths (`.env`, `pipeline/output/`, `.worktrees/`, ...) are exempt automatically, since
 * they don't exist in a clean checkout. Anything else that is legitimately absent goes here, with
 * a reason, instead of loosening the heuristics.
 */
const allowedMissing = new Set([
  ".git/config", // git internals, never tracked
  ".git/candidate-audit/", // public-repo.md: reports generated only inside an external candidate
  ".husky/_", // generated by `husky` on `prepare`
  "./availability.js", // AGENTS.md import-style example
  "./store.svelte.js", // AGENTS.md import-style example
  "./desktop.png", // development-workflow.md `--attach` example
  "static/sprites/", // sprite-assets.md: removed in #247, mentioned as history
  "scripts/measure-transfer-size.ts", // public-repo.md: deleted historical path to filter
]);

function gitIgnores(path: string): boolean {
  try {
    execFileSync("git", ["check-ignore", "-q", path], { cwd: root, stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

function isIgnored(path: string): boolean {
  // Git refuses paths beyond a symlink (exit 128), so a path under a symlinked, ignored directory
  // like `pipeline/input` only resolves through its ancestors. Each ancestor is checked with a
  // trailing slash, so directory-only patterns match one missing from disk, and without one,
  // since git refuses a symlink spelled with a trailing slash. Doc paths & git pathspecs are
  // `/`-separated on every platform, hence `posix`.
  if (gitIgnores(path)) {
    return true;
  }
  for (let ancestor = posix.dirname(path); ancestor !== "."; ancestor = posix.dirname(ancestor)) {
    if (gitIgnores(ancestor) || gitIgnores(`${ancestor}/`)) {
      return true;
    }
  }
  return false;
}

function stripCode(markdown: string): string {
  return markdown.replaceAll(/^(```|~~~)[\s\S]*?^\1/gmu, "");
}

function looksLikePath(token: string): boolean {
  if (/[\s*?{}<>[\]$|()=,;!@~^'"\\]/u.test(token) || token.includes("://")) {
    return false;
  }
  if (token.startsWith("/") || token.startsWith("#")) {
    return false;
  }
  // Only tokens anchored at a real top-level entry (or `./`, `../`) count; this skips lint rule
  // ids (`vitest/expect-expect`), branch names (`origin/main`), & other slash-separated names.
  const first = token.split("/")[0] ?? "";
  return rootEntries.has(first) || first === "." || first === "..";
}

function exists(doc: string, target: string): boolean {
  const path = target.replace(/\/$/u, "");
  return [resolve(root, path), resolve(root, dirname(doc), path)].some((candidate) =>
    existsSync(candidate),
  );
}

describe.each(docs)("%s", (doc) => {
  const text = stripCode(readFileSync(join(root, doc), "utf8"));

  it("has relative links that resolve", () => {
    const broken = [...text.matchAll(/\]\(([^)\s]+)\)/gu)]
      .map(([, link = ""]) => link.split("#")[0] ?? "")
      .filter((link) => link !== "" && !/^(?:[a-z][a-z0-9+.-]*:|\/)/iu.test(link))
      .filter((link) => !allowedMissing.has(link))
      .filter((link) => !existsSync(resolve(root, dirname(doc), decodeURI(link))));
    expect(broken).toStrictEqual([]);
  });

  it("names only repo paths that exist", () => {
    const missing = [...text.matchAll(/`([^`\n]+)`/gu)]
      .map(([, token = ""]) => token.replace(/(?::\d+(?:-\d+)?)?(?:#.*)?$/u, ""))
      .filter((token) => looksLikePath(token))
      .filter((token) => !allowedMissing.has(token) && !exists(doc, token) && !isIgnored(token));
    expect([...new Set(missing)]).toStrictEqual([]);
  });
});
